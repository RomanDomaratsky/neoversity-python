# Тема: Власний модуль mymodule.py (рекомендована фінальна версія)
# ------------------------------------------------------------------------
# Код, який має виконуватись тільки при прямому запуску файлу (python mymodule.py),
# а НЕ при імпорті цього файлу як модуля, ховаємо за перевіркою __name__.


def say_hello(name):
    return f"Hello, {name}!"


def main():
    # Прийнято весь код "точки входу" виносити в функцію main() -
    # так модуль лишається чистим при імпорті і придатним для запуску напряму.
    print("You imported hello.py")
    print(say_hello("user"))


if __name__ == "__main__":
    # __name__ == "__main__", тільки якщо файл запущено безпосередньо:
    # python mymodule.py. При імпорті (import mymodule) __name__ буде
    # рівний "mymodule", і цей блок НЕ виконається.
    main()
