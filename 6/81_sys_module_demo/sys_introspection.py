# Тема: Модуль sys - інтроспекція середовища Python
# ------------------------------------------------------------------------

import sys
import os

# sys.modules - словник усіх ЗАВАНТАЖЕНИХ на даний момент модулів
print(sys.modules["os"])  # <module 'os' from '...'>

# Повний список імен завантажених модулів
print(list(sys.modules.keys())[:10], "...")  # показуємо перші 10 для стислості

# sys.builtin_module_names - модулі, вбудовані прямо в інтерпретатор
print(sys.builtin_module_names)

# sys.path - список директорій, де Python шукає модулі під час імпорту.
# Порядок важливий: пошук йде по черзі, першим знайдений модуль переможе.
# Практичне застереження: якщо назвати свій скрипт, наприклад, random.py,
# то import random підхопить ваш файл замість стандартного модуля random,
# бо робоча директорія перевіряється РАНІШЕ за стандартну бібліотеку.
print(sys.path)

# sys.version - версія Python, що використовується
print(sys.version)

# sys.platform - назва платформи ('win32', 'linux', 'darwin' тощо)
print(sys.platform)
