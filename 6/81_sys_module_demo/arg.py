import sys


def main():
    # Завжди перевіряйте кількість аргументів, перш ніж звертатися до них
    if len(sys.argv) > 1:
        print(sys.argv[1])
    else:
        print("Аргумент не передано. Приклад запуску: python arg.py 123")


if __name__ == "__main__":
    main()
