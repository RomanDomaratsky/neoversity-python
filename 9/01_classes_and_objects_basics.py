# Тема: Основи ООП - класи та об'єкти
# ------------------------------------------------------------------------
# Клас - структура, що об'єднує дані (поля, атрибути) та функції (методи).
# Об'єкт - конкретний екземпляр класу (метафора: клас - форма для випічки,
# об'єкт - готове печиво заданої формою, але з різною "начинкою").

# Найпростіший клас: порожнє тіло за допомогою pass
class Person:
    pass


p = Person()
print(type(p))  # <class '__main__.Person'>


# Клас з атрибутами класу (спільні значення за замовчуванням для всіх об'єктів)
class User:
    name = 'Anonymous'
    age = 15


user1 = User()
print(user1.name)  # Anonymous
print(user1.age)   # 15

user2 = User()
user2.name = "John"
user2.age = 90
print(user2.name)  # John
print(user2.age)   # 90

# user1 залишився незмінним - у кожного об'єкта своя "начинка"
print(user1.name)  # Anonymous
print(user1.age)   # 15

