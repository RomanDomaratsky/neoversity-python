# Тема: Генератор для читання великих файлів "рядок за раз" (лінива обробка)
# ------------------------------------------------------------------------------
# Практичне застосування: обробка величезних лог-файлів чи CSV, які не
# поміщаються в пам'ять цілком - генератор читає й обробляє один рядок
# за раз, не завантажуючи весь файл одразу.


def read_lines(file_path):
    with open(file_path, 'r', encoding="utf-8") as file:
        for line in file:
            yield line.strip()


# Створимо невеликий демонстраційний файл, щоб приклад можна було запустити
with open("my_file.txt", "w", encoding="utf-8") as f:
    f.write("Перший рядок\nДругий рядок\nТретій рядок\n")

# Використання генератора для читання рядків із файлу
for line in read_lines("my_file.txt"):
    print(line)
# Перший рядок
# Другий рядок
# Третій рядок

# Прибираємо демонстраційний файл
import os
os.remove("my_file.txt")
