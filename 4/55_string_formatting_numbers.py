# Тема: Форматування рядків та чисел (f-рядки)
# ---------------------------------------------------

# Різні системи представлення чисел: десяткова, hex, octal, binary
for i in range(8):
    s = f"int: {i:d};  hex: {i:#x};  oct: {i:#o};  bin: {i:#b}"
    print(s)

# Форматування з фіксованою точністю (:.2f - два знаки після крапки)
# Практичне застосування: обов'язковий формат для грошових сум у
# рахунках, звітах чи інтернет-магазинах, де потрібні рівно 2 знаки
# після коми незалежно від результату обчислень.
price = 19.99
quantity = 3
total = f"Total: {price * quantity:.2f}"
print(total)  # Total: 59.97

# Вирівнювання по центру із заданою шириною поля (таблиця квадратів і кубів)
for num in range(12):
    print(f'{num:^10} {num**2:^10} {num**3:^10}')

# Вирівнювання праворуч ( > ), ширина поля 10 символів
name = "Alice"
formatted = f"{name:>10}"
print(formatted)  # "     Alice"

# Вирівнювання ліворуч ( < ) та по центру ( ^ ) - для порівняння
print(f"{name:<10}|")  # "Alice     |"
print(f"{name:^10}|")  # "  Alice   |"

# Форматування відсотків ({:.1%} - множить на 100 і додає %)
# Практичне застосування: зручно для прогрес-барів, звітів про виконання
# завдань чи відображення частки завершеної роботи у консольних утилітах.
completion = 0.756
formatted = f"{completion:.1%}"
print(formatted)  # 75.6%

progress = 0.5
formatted = f"{progress:.0%}"
print(formatted)  # 50%
