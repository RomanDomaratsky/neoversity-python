# Тема: Черга (Queue) - FIFO (First In, First Out), реалізована через deque
# ------------------------------------------------------------------------------
# Списки Python неефективні для видалення елементів з початку (потрібно
# перенумерувати всі решта елементів). deque з collections оптимізований
# для швидких операцій на обох кінцях, тому саме він рекомендований для черг.
# Практичне застосування: черги моделюють обробку задач у порядку надходження -
# черги повідомлень, обробку запитів на сервері, друк документів тощо.

from collections import deque

queue = deque()

# Enqueue - додавання елементів у кінець черги
queue.append('a')
queue.append('b')
queue.append('c')
print("Черга після додавання елементів:", list(queue))  # ['a', 'b', 'c']

# Dequeue - видалення елемента з початку черги
print("Видалений елемент:", queue.popleft())  # 'a'
print("Черга після видалення елемента:", list(queue))  # ['b', 'c']

# Peek - перегляд першого елемента без видалення
print("Перший елемент у черзі:", queue[0])  # 'b'

# IsEmpty та Size
print("Чи черга порожня:", len(queue) == 0)  # False
print("Розмір черги:", len(queue))            # 2
