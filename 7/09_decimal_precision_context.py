# Тема: Контроль точності обчислень Decimal - getcontext().prec
# ------------------------------------------------------------------------
# getcontext().prec встановлює кількість ЗНАЧУЩИХ цифр (не тільки після
# коми - цифри до коми теж рахуються значущими).

from decimal import Decimal, getcontext

getcontext().prec = 6
print(Decimal("1") / Decimal("7"))  # 0.142857 (6 значущих цифр)

getcontext().prec = 8
print(Decimal("1") / Decimal("7"))  # 0.14285714 (8 значущих цифр)


# Приклад, де значущі цифри включають і цифри ДО коми
getcontext().prec = 6
print(type(Decimal("233") / Decimal("7")))  # 33.2857 (рівно 6 значущих цифр)

# Правила значущих цифр (довідково):
# - усі ненульові цифри значущі: 1,2,3...9
# - нулі МІЖ ненульовими цифрами значущі: 102, 2005
# - провідні нулі НЕ значущі: 0.02, 0.000515
# - "хвостові" нулі після коми значущі, якщо обґрунтовані точністю: 389.000
