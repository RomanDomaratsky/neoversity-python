# Тема: Двостороння черга deque - додавання/видалення з ОБОХ кінців
# ------------------------------------------------------------------------------
# append(x)     - додає в кінець
# appendleft(x) - додає на початок
# pop()         - видаляє та повертає елемент з правого кінця
# popleft()     - видаляє та повертає елемент з лівого кінця

from collections import deque

d = deque()

d.append('middle')
d.append('last')
d.appendleft('first')
print("Черга після додавання елементів:", list(d))  # ['first', 'middle', 'last']

print("Видалений останній елемент:", d.pop())       # 'last'
print("Видалений перший елемент:", d.popleft())     # 'first'
print("Черга після видалення елементів:", list(d))  # ['middle']


# maxlen - обмеження розміру deque: нові елементи витісняють найстаріші
# Практичне застосування: ідеально для "ковзного вікна" останніх N подій -
# наприклад, останні N повідомлень у чаті, останні N вимірів датчика тощо.
d = deque(maxlen=5)
for i in range(10):
    d.append(i)
print(d)  # deque([5, 6, 7, 8, 9], maxlen=5)
