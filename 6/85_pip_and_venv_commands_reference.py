# Цей файл - шпаргалка. Усі рядки нижче виконуються в терміналі/командному
# рядку (CMD, PowerShell, bash), а НЕ шляхом запуску цього .py файлу.

# --- pip: перегляд встановлених пакетів ---
# python -m pip list                     # список пакетів (через модуль)
# pip list                               # те саме, якщо pip доступний напряму
# pip freeze                             # список пакетів у форматі name==version

# --- pip: встановлення / видалення пакетів ---
# pip install requests                   # встановити останню версію
# pip install requests==2.28.2           # встановити КОНКРЕТНУ версію
# pip install requests>=2.28.2           # версія не старіша за вказану
# pip install requests<=2.28.2           # версія не новіша за вказану
# pip uninstall requests                 # видалити пакет

# --- requirements.txt: фіксація та відновлення залежностей проєкту ---
# Практичне застосування: requirements.txt дозволяє іншому розробнику
# (або серверу деплою) відновити ТОЧНО таке саме середовище, як у вас,
# однією командою - критично важливо для командної роботи та CI/CD.
# pip freeze > requirements.txt          # згенерувати файл залежностей
# pip install -r requirements.txt        # встановити всі залежності з файлу

# --- venv: створення й керування віртуальним оточенням ---
# python -m venv .venv                   # створити віртуальне оточення в .venv/

# Активація (залежить від ОС та командного інтерпретатора):
# .\.venv\Scripts\activate.bat           # Windows CMD
# .\.venv\Scripts\Activate.ps1           # Windows PowerShell
# source .venv/bin/activate              # macOS / Linux

# deactivate                             # повернутися до системного Python

# Видалення віртуального оточення - просто видаліть директорію .venv/ фізично.

# --- Практичне застереження ---
# Встановлення пакетів у СИСТЕМНИЙ Python (без venv) може призвести до
# конфлікту версій між різними проєктами: один проєкт вимагає requests==2.28,
# інший - requests==2.31, і глобально задовольнити обидва одночасно
# неможливо. Віртуальне оточення ізолює залежності кожного проєкту окремо.
