# Тема: Модуль decimal - точна арифметика з дійсними числами
# ------------------------------------------------------------------------
# float має похибку округлення через двійкове представлення дробів.
# Decimal розв'язує цю проблему - важливо для фінансових розрахунків,
# де помилки округлення можуть призводити до серйозних наслідків.

print(0.1 + 0.2 == 0.3)  # False (!) - похибка округлення float
print(0.1 + 0.2)         # 0.30000000000000004

from decimal import Decimal

print(Decimal("0.1") + Decimal("0.2") == Decimal("0.3"))  # True
print(Decimal("0.1") + Decimal("0.2"))                     # 0.3

# ВАЖЛИВО: Decimal створюють з рядка ("0.1"), а не з float (0.1) -
# інакше похибка float потрапить усередину Decimal ще до створення об'єкта.

# Decimal і float НЕ можна змішувати в одному виразі - буде помилка TypeError:
Decimal("0.1") + 0.2  # розкоментуй, щоб побачити помилку
