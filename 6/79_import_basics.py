# Тема: Основи імпорту модулів (import, from ... import ...)
# ------------------------------------------------------------------------

import math

sin_pi = math.sin(math.pi)
print(sin_pi)  # ~1.2246467991473532e-16 (майже 0, через похибку float)

# Аналогічний результат через вибірковий імпорт конкретних імен
from math import pi, sin

sin_pi = sin(pi)
print(sin_pi)

# Імпорт з псевдонімом (alias) - корисно для уникнення конфліктів імен
# або для скорочення довгих/незрозумілих назв
from math import sqrt as square_root

print(square_root(16))  # 4.0

