# Тема: Регулярні вирази - метод re.sub()
# ---------------------------------------------
# re.sub(pattern, repl, string) замінює всі входження шаблону на repl.

import re

# Заміна пробілів на підкреслення в назві файлу
# Практичне застосування: уникнення проблем зі шляхами в операційних
# системах, спрощення роботи з файлом через командний рядок та
# забезпечення сумісності з URL (де пробіли не дозволені).
file_name = "Мій документ Python.txt"
pattern = r"\s"
replacement = "_"
formatted_name = re.sub(pattern, replacement, file_name)
print(formatted_name)  # Мій_документ_Python.txt

# Видалення пунктуаційних знаків з тексту
text = "Python - потужна, універсальна; мова!"
pattern = r"[;,\-:!\.]"
replacement = ""
modified_text = re.sub(pattern, replacement, text)
print(modified_text)  # Python  потужна універсальна мова

# Форматування телефонних номерів за допомогою груп
# Практичне застосування: нормалізація даних з різних джерел
# (наприклад, імпорт контактів) до єдиного стандартного формату.
phone = """
        Михайло Куліш: 050-171-1634
        Вікторія Кущ: 063-134-1729
        Оксана Гавриленко: 068-234-5612
        """
pattern = r"(\d{3})-(\d{3})-(\d{4})"
replacement = r"(\1) \2-\3"
formatted_phone = re.sub(pattern, replacement, phone)
print(formatted_phone)
# Михайло Куліш: (050) 171-1634
# Вікторія Кущ: (063) 134-1729
# Оксана Гавриленко: (068) 234-5612
