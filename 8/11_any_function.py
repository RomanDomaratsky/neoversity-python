# Тема: Функція any() - True, якщо ХОЧА Б ОДИН елемент істинний
# ------------------------------------------------------------------------
# Порожній об'єкт ітерації або всі елементи хибні -> any() поверне False.

nums = [0, False, 5, 0]
result = any(nums)
print(result)  # True (бо 5 - істинне значення)

# any() з генераторним виразом: чи є у списку парні числа?
nums = [1, 3, 5, 7, 9]
result = any(x % 2 == 0 for x in nums)
print(result)  # False (парних чисел немає)

# Практичне застосування: швидка перевірка "чи хоч щось відповідає умові" -
# наприклад, чи є серед введених даних хоча б одне некоректне значення,
# без явного циклу for з break.
errors = ["", "", "Файл не знайдено", ""]
has_errors = any(errors)
print(has_errors)  # True
