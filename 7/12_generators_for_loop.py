# Тема: Генератори у циклі for (без ручного next()/StopIteration)
# ------------------------------------------------------------------------
# Цикл for сам викликає next() і сам коректно "ловить" StopIteration -
# тому генератори найчастіше використовують саме в for, а не вручну.
# Підказка: вбудована функція range() - це типовий приклад генератора.


def count_down(start):
    while start > 0:
        yield start
        start -= 1


for number in count_down(5):
    print(number)
# 5
# 4
# 3
# 2
# 1
