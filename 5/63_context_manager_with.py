# Тема: Менеджер контексту with для роботи з файлами
# ------------------------------------------------------------

# Без менеджера контексту: потрібен try/finally, щоб файл ГАРАНТОВАНО закрився
fh = open('text.txt', 'w')
try:
    fh.write('Some data')
finally:
    fh.close()

# Практичне застосування: у реальному коді (веб-сервіси, скрипти обробки
# даних, що працюють без нагляду) забутий незакритий файл - поширена причина
# витоку дескрипторів і пошкоджених файлів. Конструкція `with` вирішує цю
# проблему автоматично і є стандартом де-факто в Python-коді.
with open('text.txt', 'w') as fh:
    fh.write('Some data')
# Файл автоматично закриється після виходу з блоку with, навіть якщо
# всередині блоку виникне виняток.


# Перепишемо приклад читання файлу з попередньої теми через with
with open("test.txt", "w") as fh:
    fh.write("first line\nsecond line\nthird line")

with open("test.txt", "r") as fh:
    lines = [el.strip() for el in fh.readlines()]

print(lines)  # ['first line', 'second line', 'third line']
