# Під час імпорту модуля Python виконує ВЕСЬ код усередині нього.
# Якщо код виклику функції не захищений через if __name__ == "__main__",
# він виконається щоразу, коли хтось просто ІМПОРТУЄ цей модуль -
# навіть якщо викликач хотів лише отримати функцію say_hello, а не
# запускати демонстраційний вивід.


def say_hello(name):
    print(f'Hello, {name}')


