# Тема: Регулярні вирази - метод re.split()
# ------------------------------------------------
# re.split(pattern, string) розбиває рядок за шаблоном (складнішим,
# ніж фіксований роздільник у звичайному str.split()).

import re

# Розбиття рядка за одним або кількома пробільними символами
text = "Python - це проста, але потужна мова програмування."
pattern = r"\s+"
words = re.split(pattern, text)
print(words)
# ['Python', '-', 'це', 'проста,', 'але', 'потужна', 'мова', 'програмування.']

# Розбиття за набором пунктуаційних знаків і пробілів одночасно
text = "Python - потужна; проста, універсальна: мова!"
pattern = r"[;,\-:!\s]+"
elements = re.split(pattern, text)
print(elements)
# ['Python', 'потужна', 'проста', 'універсальна', 'мова', '']
# Останній елемент порожній, бо рядок закінчується роздільником ("!").
# Прибрати його можна зрізом: elements[:-1]

# Розбиття за кількома різними символами-роздільниками одночасно
# (звичайний str.split() з одним роздільником так не зможе)
text = "apple#banana!mango@orange;kiwi"
pattern = r"[#@;!]"
fruits = re.split(pattern, text)
print(fruits)  # ['apple', 'banana', 'mango', 'orange', 'kiwi']
