# Тема: Лямбда-функції (анонімні функції)
# ------------------------------------------------------------------------
# Синтаксис: lambda arguments: expression
# Лямбда може містити ТІЛЬКИ один вираз (без циклів, without if-блоків).

# Присвоєння лямбди змінній (можливо, але не найкращий стиль)
add = lambda x, y: x + y
print(add(5, 3))  # 8

# Кращий стиль - лямбда створюється одразу там, де використовується,
# і не залишається "слідів" у просторі імен
print((lambda x, y: x + y)(5, 3))  # 8


# Практичне застосування: лямбди найчастіше використовуються як key= для
# sorted()/min()/max(), а також з map()/filter() - для короткої "формули"
# перетворення чи умови, коли повноцінна функція буде зайвою.
nums = [1, 2, 3, 4, 5]
nums_sorted = sorted(nums, key=lambda x: -x)
print(nums_sorted)  # [5, 4, 3, 2, 1]
