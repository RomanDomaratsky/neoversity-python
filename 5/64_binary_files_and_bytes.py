# Тема: Робота з нетекстовими (бінарними) файлами та типом bytes
# ------------------------------------------------------------------------
# Режим 'b' (bytes) - для роботи з "сирими"/двійковими даними.

# Запис бінарних даних у файл
with open('raw_data.bin', 'wb') as fh:
    fh.write(b'Hello world!')

# Байтовий рядок (bytes) - незмінний тип, один символ = один байт
byte_string = b'Hello world!'
print(byte_string)

# До байтових рядків застосовні ті самі методи, що й до звичайних рядків
print(byte_string.upper())        # b'HELLO WORLD!'
print(byte_string.startswith(b'Hello'))  # True

# Індексація байтового рядка повертає ЧИСЛО (код символу), а не символ
s = b'Hello!'
print(s[1])  # 101 - це ASCII-код символу 'e'

# Приклади ASCII-кодів для довідки:
# цифри '0'-'9' -> 48-57; великі літери 'A'-'Z' -> 65-90;
# малі літери 'a'-'z' -> 97-122; пробіл -> 32; '!' -> 33; '@' -> 64
